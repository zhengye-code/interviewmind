-- V6: 面试评分结果（M6）

-- ① 逐题评分：一道题一行
CREATE TABLE interview_question_scores (
                                           id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           session_id          BIGINT       NOT NULL,
                                           question_id         BIGINT       NOT NULL,
                                           score               INTEGER      NOT NULL,
                                           hit_points_json     TEXT,
                                           missed_points_json  TEXT,
                                           comment             TEXT,
                                           created_at          TIMESTAMP(6) NOT NULL,
                                           CONSTRAINT fk_iqs_session
                                               FOREIGN KEY (session_id) REFERENCES interview_sessions(id) ON DELETE CASCADE,
                                           CONSTRAINT fk_iqs_question
                                               FOREIGN KEY (question_id) REFERENCES interview_questions(id) ON DELETE CASCADE,
                                           CONSTRAINT uk_iqs_question UNIQUE (question_id),
                                           CONSTRAINT ck_iqs_score CHECK (score BETWEEN 0 AND 10)
);

CREATE INDEX idx_iqs_session ON interview_question_scores(session_id);

-- ② 整场报告：一场面试一行
CREATE TABLE interview_reports (
                                   id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   session_id          BIGINT       NOT NULL,
                                   overall_score       INTEGER      NOT NULL,
                                   summary             TEXT,
                                   strengths_json      TEXT,
                                   suggestions_json    TEXT,
                                   model               VARCHAR(100),
                                   evaluated_at        TIMESTAMP(6) NOT NULL,
                                   CONSTRAINT fk_ir_session
                                       FOREIGN KEY (session_id) REFERENCES interview_sessions(id) ON DELETE CASCADE,
                                   CONSTRAINT uk_ir_session UNIQUE (session_id),
                                   CONSTRAINT ck_ir_score CHECK (overall_score BETWEEN 0 AND 100)
);

CREATE INDEX idx_ir_evaluated ON interview_reports(evaluated_at DESC);