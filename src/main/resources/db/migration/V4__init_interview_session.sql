-- V4: 面试会话与题目
CREATE TABLE interview_sessions (
                                    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    skill_id               VARCHAR(64)  NOT NULL,
                                    resume_id              BIGINT,
                                    status                 VARCHAR(20)  NOT NULL,
                                    difficulty             VARCHAR(20)  NOT NULL,
                                    total_questions        INTEGER      NOT NULL,
                                    current_question_index INTEGER      NOT NULL DEFAULT 0,
                                    plan_json              TEXT         NOT NULL,
                                    version                INTEGER      NOT NULL DEFAULT 0,
                                    created_at             TIMESTAMP(6) NOT NULL,
                                    updated_at             TIMESTAMP(6) NOT NULL,
                                    finished_at            TIMESTAMP(6),
                                    CONSTRAINT fk_interview_sessions_resume
                                        FOREIGN KEY (resume_id) REFERENCES resumes(id) ON DELETE SET NULL
);

CREATE INDEX idx_interview_sessions_skill ON interview_sessions(skill_id);
CREATE INDEX idx_interview_sessions_created ON interview_sessions(created_at DESC);

CREATE TABLE interview_questions (
                                     id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     session_id      BIGINT      NOT NULL,
                                     question_index  INTEGER     NOT NULL,
                                     category_key    VARCHAR(64) NOT NULL,
                                     difficulty      VARCHAR(20) NOT NULL,
                                     question_text   TEXT        NOT NULL,
                                     expected_points TEXT,
                                     asked_at        TIMESTAMP(6),
                                     CONSTRAINT fk_interview_questions_session
                                         FOREIGN KEY (session_id) REFERENCES interview_sessions(id) ON DELETE CASCADE,
                                     CONSTRAINT uk_interview_questions_order
                                         UNIQUE (session_id, question_index)
);

CREATE INDEX idx_interview_questions_session ON interview_questions(session_id);